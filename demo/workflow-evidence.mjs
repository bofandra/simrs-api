export function recordEvidence(session, command, values, at) {
  for (const [kind, status] of Object.entries(transitions[command] ?? {})) {
    const prior = session.evidence[kind];
    session.evidence[kind] = {
      kind, label: evidenceLabels[kind], id: prior?.id ?? kind.toUpperCase() + '-' + session.id.slice(0, 8).toUpperCase(),
      status: typeof status === 'function' ? status(values) : status,
      updatedAt: at, version: (prior?.version ?? 0) + 1,
      patientId: session.patient.id, episodeId: session.episodeId,
    };
  }
}
